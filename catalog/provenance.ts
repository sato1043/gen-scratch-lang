/**
 * 手書きの表の出典を機械可読に持つ。
 *
 * 各表の先頭コメントは出典を散文で書いているが、散文は照合に使えない。上流の版が
 * 上がったとき、どの表を確かめ直すべきかを機械で示せるようにする。
 *
 * ここは台帳の中身を与えない。台帳の生成元ではなく、生成元についての記録である。
 *
 * `種別` は再導出できるかで分ける。
 *
 * | 種別 | 意味 |
 * |---|---|
 * | `導出` | 上流の現在の版から書き出し直せる。照合で見張る |
 * | `旧版` | 上流が定義を失っており、現在の版からは書き出せない |
 * | `別出典` | 依存に持たないパッケージから写した |
 * | `手書き` | 機械では導けない。設計上の判断を含む |
 *
 * `確認した現行版` は、その表を最後に確かめたときの scratch-blocks の版である。今の版が
 * これと違えば、確かめ直しが要る（何がどう変わったかまでは分からない。分かるのは
 * 確かめた前提が動いたことだけである）。
 */

type Source = {
  表: string
  種別: "導出" | "旧版" | "別出典" | "手書き"
  出典: string
  /** 出典の版。手書きなら null */
  版: string | null
  /** 確かめた時点の scratch-blocks の版 */
  確認した現行版: string
  /** なぜその種別なのか */
  理由: string
}

